/******************************************************************************
* Global Variables
******************************************************************************/
uint16_t timer_cnt=0;
uint8_t timer_task_10ms=0, timer_task_100ms=0, timer_task_500ms=0, timer_task_1s=0;

/******************************************************************************
* External Variables
******************************************************************************/


/******************************************************************************
* Local Function Declarations
******************************************************************************/
void timer_init(void);
uint8_t check_timer_compare(void);
void port_init(void);
/******************************************************************************
* Local Function Definitions
******************************************************************************/

uint8_t check_timer_compare(void)
{
	if((TIFR0 & (1<<OCF0A)) == (1<<OCF0A))
	{
		TIFR0 = TIFR0 | (1<<OCF0A);
		return 1;
	}
	return 0;
}

void timer_init(void)
{
	//TCCR0A = 0b00001101;
	TCCR0A = (0<<FOC0A) | (0<<WGM00) | (0<<COM0A1) | (0<<COM0A0) | (1<<WGM01) | (1<<CS02) | (0<<CS01) | (1<<CS00);
	OCR0A = 77;
}

void port_init(void)
{
	DDRA = (1<<PA3) | (1<<PA2) | (1<<PA1) | (1<<PA0);
	PORTA = (1<<PA3) | (1<<PA2) | (1<<PA1) | (1<<PA0);
}

/******************************************************************************
* Function:         int main(void)
* Description:      main function
* Input:            
* Output:           
* Notes:            
******************************************************************************/
int main(void)
{
	port_init();
	timer_init();
	
	while(1)
	{
		if(check_timer_compare())
		{
			timer_cnt++;
			if((timer_cnt % 1) == 0) timer_task_10ms =1;
			if((timer_cnt % 10) == 0) timer_task_100ms =1;
			if((timer_cnt % 50) == 0) timer_task_500ms =1;
			if((timer_cnt % 100) == 0) timer_task_1s =1;
			
		}
		if(timer_task_10ms)
		{
			PORTA ^=(1<<PA0);
			timer_task_10ms=0;
		}
		
		if(timer_task_100ms)
		{
			PORTA ^=(1<<PA1);
			timer_task_100ms=0;
		}
		
		if(timer_task_500ms)
		{
			PORTA ^=(1<<PA2);
			timer_task_500ms=0;
		}
		if(timer_task_1s)
		{
			PORTA ^=(1<<PA3);
			timer_task_1s=0;
		}
	}
}


