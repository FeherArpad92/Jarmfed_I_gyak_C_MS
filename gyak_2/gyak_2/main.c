/******************************************************************************
* Global Variables
******************************************************************************/
uint16_t timer_cnt=0;
uint8_t timer_task_10ms=0, timer_task_100ms=0, timer_task_500ms=0, timer_task_1s=0;

/******************************************************************************
* External Variables
******************************************************************************/


/******************************************************************************
* Local Function Declarations
******************************************************************************/
void timer_init(void);
uint8_t check_timer_compare(void);
/******************************************************************************
* Local Function Definitions
******************************************************************************/
uint8_t check_timer_compare(void)
{
	if((TIFR0 & (1<<OCF0A)) == (1<<OCF0A))
	{
		TIFR0 = TIFR0 | (1<<OCF0A);
		return 1;
	}
	return 0;
}

void timer_init(void)
{
	//TCCR0A = 0b00001101;
	TCCR0A = (0<<WGM00) | (1<<WGM01) | (1<<CS02) | (0<<CS01) | (1<<CS00);
	OCR0A = 77;
}

/******************************************************************************
* Function:         int main(void)
* Description:      main function
* Input:            
* Output:           
* Notes:            
******************************************************************************/
int main(void)
{
	DDRB = (1<<PB3) | (1<<PB2) | (1<<PB1) | (1<<PB0);
	
	timer_init();
	/* Replace with your application code */
	while(1)
	{
		if(check_timer_compare())
		{
			timer_cnt++;
			timer_task_10ms = 1;
			if((timer_cnt % 10)==0) timer_task_100ms = 1;
			if((timer_cnt % 50)==0) timer_task_500ms = 1;
			if((timer_cnt % 100)==0) timer_task_1s = 1;
		}

		if(timer_task_10ms)
		{
			PORTB ^=(1<<PB0);
			timer_task_10ms=0;
		}
		if(timer_task_100ms)
		{
			PORTB ^=(1<<PB1);
			timer_task_100ms=0;
		}
		if(timer_task_500ms)
		{
			PORTB ^=(1<<PB2);
			timer_task_500ms=0;
		}
		if(timer_task_1s)
		{
			PORTB ^=(1<<PB3);
			timer_task_1s=0;
		}
	}
}


