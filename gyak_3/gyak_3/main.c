/******************************************************************************
* Global Variables
******************************************************************************/
int irany=0;
int timer_cnt=0;
int timer_task_10ms=0, timer_task_100ms=0, timer_task_500ms=0;

/******************************************************************************
* External Variables
******************************************************************************/


/******************************************************************************
* Local Function Declarations
******************************************************************************/
void port_init(void);
void timer_init(void);
int check_timer_compare(void);

/******************************************************************************
* Local Function Definitions
******************************************************************************/
void port_init(void)
{
	DDRA=0xff;
	PORTA = 0x00;
}

void timer_init(void)
{
	TCCR0A = (1<<WGM01) | (0<<WGM00) | (1<<CS02) | (0<<CS01) | (1<<CS00);
	OCR0A = 77;
}

int check_timer_compare(void)
{
	if((TIFR0 & (1<<OCF0A)) == (1<<OCF0A))
	{
		TIFR0 = TIFR0 | (1<<OCF0A);
		return 1;
	}
	return 0;
}

/******************************************************************************
* Function:         int main(void)
* Description:      main function
* Input:            
* Output:           
* Notes:            
******************************************************************************/
int main(void)
{
	port_init();
	PORTA = 0x01;
	timer_init();
	
	/* Replace with your application code */
	while(1)
	{
		
		if(check_timer_compare())
		{
			timer_cnt++;
			
			if((timer_cnt % 1) == 0) timer_task_10ms =1;
			if((timer_cnt % 10) == 0) timer_task_100ms =1;
			if((timer_cnt % 50) == 0) timer_task_500ms =1;
			
			if(timer_task_10ms)
			{
				
				timer_task_10ms=0;
			}
			
			if(timer_task_100ms)
			{
				
				timer_task_100ms=0;
			}
			
			if(timer_task_500ms)
			{
				if(irany==0)
				{
					PORTA = PORTA << 1;
				}
				else
				{
					PORTA = PORTA >> 1;
				}
				
				if(PORTA==0x80) irany=1;
				if(PORTA==0x01) irany=0;
				timer_task_500ms=0;
			}
			
			
		}
		

			
			

		
		//PORTA = PORTA ^ 0xff;
		//PORTA = PORTA * 2;
		
		
		
		//_delay_ms(50);
		//for(long int i=0;i<100000;i++);
	}
}


