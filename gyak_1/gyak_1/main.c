int main(void)
{
	DDRB = 0xFF;
	
	PORTB = 0b00000001;
	int dir=0;
	/* Replace with your application code */
	while(1)
	{
		for(long int i =0; i<100000;i++);
		
		if(dir==0) PORTB = PORTB*2;
		if(dir==1) PORTB = PORTB/2;
		
		if(PORTB == 0b10000000) dir = 1;
		
		if(PORTB == 0b00000001) dir = 0;
		
		//PORTB = PORTB ^ 0b00000001;
		
	}
}


